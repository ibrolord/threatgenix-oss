_CITATION_RE = re.compile(
    r"(?:T\d{4}(?:\.\d{3})?|CAPEC-\d+|CWE-\d+)"
)


def _extract_citations(description: str, db_citations: list[Any] | None) -> list[str]:
    """Extract ATT&CK/CAPEC/CWE citation IDs from description text and DB column."""
    found: list[str] = []
    # From description text inline references
    found.extend(_CITATION_RE.findall(description))
    # From DB citations column (list of dicts with 'id' key, or plain strings)
    for item in db_citations or []:
        if isinstance(item, str):
            found.extend(_CITATION_RE.findall(item))
        elif isinstance(item, dict) and "id" in item:
            found.extend(_CITATION_RE.findall(str(item["id"])))
    # Deduplicate while preserving order
    seen: set[str] = set()
    result: list[str] = []
    for cid in found:
        if cid not in seen:
            seen.add(cid)
            result.append(cid)
    return result


def _derive_mitigation_status(threat: ThreatResponse) -> str:
    if threat.status in ("In Progress", "Mitigated"):
        return threat.status
    if (
        threat.mitigation_plan
        or threat.mitigation_owner
        or threat.due_date is not None
        or threat.mitigation_notes
    ):
        return "Planned"
    return ""


def _truncate_list(values: list[str], *, limit: int = 8) -> list[str]:
    return [value for value in values if value][:limit]


def _normalize_assumptions(raw_assumptions: list[dict[str, Any]] | None) -> list[ThreatModelAssumptionResponse]:
    normalized: list[ThreatModelAssumptionResponse] = []
    for item in raw_assumptions or []:
        try:
            normalized.append(ThreatModelAssumptionResponse.model_validate(item))
        except Exception:
            continue
    return sorted(normalized, key=lambda item: item.updated_at, reverse=True)


